'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const src=fs.readFileSync('home-services.html','utf8');
const begin=src.indexOf('function ocsBookingLocationHTML(){');
const end=src.indexOf('\nconst services=',begin);
assert(begin>=0&&end>begin,'Booking location UI functions must exist');
const location=src.slice(begin,end);
assert.match(location,/Sirf area\/pincode likhna kaafi nahi hai/,'Manual area must not imply valid GPS booking pin');
assert.match(location,/Update Location Pin/,'Saved pin must be updatable');
assert.match(location,/Number\.isFinite\(lat\)/,'GPS latitude must be finite');
assert.match(location,/Number\.isFinite\(lng\)/,'GPS longitude must be finite');
assert.match(location,/lat===0&&lng===0/,'Zero coordinates must be rejected');
const start=src.indexOf('async function ocsCreateLiveBooking(){');
const stop=src.indexOf('async function ocsProviderDecisionLive(d){',start);
assert(start>=0&&stop>start,'Live booking function must exist');
const booking=src.slice(start,stop);
assert.match(booking,/Booking location missing or invalid/,'Invalid GPS pin must block booking');
assert.match(booking,/p_latitude:Number\(S\.customerBookingLat\)/,'GPS latitude must be sent to backend');
assert.match(booking,/p_longitude:Number\(S\.customerBookingLng\)/,'GPS longitude must be sent to backend');
console.log('PASS booking GPS location UI and backend contract (static only)');
