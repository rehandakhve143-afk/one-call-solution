-- Recover schema dependencies for customer booking RPC in disposable CI.
CREATE TABLE IF NOT EXISTS public.service_categories (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_key text NOT NULL,
 category_name text NOT NULL,
 icon text,
 active boolean NOT NULL DEFAULT true,
 sort_order integer NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.service_catalog (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 category_id bigint NOT NULL REFERENCES public.service_categories(id),
 service_name text NOT NULL,
 service_type text NOT NULL DEFAULT 'fixed',
 unit_price numeric,
 display_price text,
 active boolean NOT NULL DEFAULT true,
 sort_order integer NOT NULL DEFAULT 0,
 metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.service_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service_catalog ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ADD COLUMN IF NOT EXISTS service_id uuid REFERENCES public.service_catalog(id);
ALTER TABLE public.bookings ADD COLUMN IF NOT EXISTS selected_items jsonb NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE public.bookings ADD COLUMN IF NOT EXISTS booking_readiness jsonb NOT NULL DEFAULT '{}'::jsonb;
